import AppKit

public enum ReadResult: Equatable, Sendable {
    case clip(ClipDraft), concealed, tooLarge, ownWrite, empty
}

/// File clips keep their URLs under this key, one absolute URL string per line.
let fileListType = NSPasteboard.PasteboardType.fileURL.rawValue

public enum PasteboardReader {
    public static let maxBytes = 25 * 1024 * 1024

    // nspasteboard.org markers that password managers and generated content set (#8).
    static let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                         "org.nspasteboard.AutoGeneratedType"]
    static let richTypes: Set<String> = [NSPasteboard.PasteboardType.rtf.rawValue,
                                         NSPasteboard.PasteboardType.rtfd.rawValue,
                                         NSPasteboard.PasteboardType.html.rawValue]
    static let imageTypes: Set<String> = [NSPasteboard.PasteboardType.png.rawValue,
                                          NSPasteboard.PasteboardType.tiff.rawValue, "public.jpeg"]

    public static func read(_ pb: NSPasteboard, sourceBundleID: String?) -> ReadResult {
        let types = Set((pb.types ?? []).map(\.rawValue))
        if types.isEmpty { return .empty }
        if types.contains(PasteboardWriter.ownType.rawValue) { return .ownWrite }
        if !types.isDisjoint(with: skipTypes) { return .concealed }

        let files = (pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
        if !files.isEmpty {
            let list = Data(files.map(\.absoluteString).joined(separator: "\n").utf8)
            return .clip(ClipDraft(formats: [fileListType: list], plainText: nil, fileURLs: files, kind: .file,
                                   contentHash: ContentHash.of(files: files), sourceBundleID: sourceBundleID))
        }

        var formats: [String: Data] = [:]
        var total = 0
        for type in pb.pasteboardItems?.first?.types ?? [] {
            guard let d = pb.pasteboardItems?.first?.data(forType: type) else { continue }
            total += d.count
            if total > maxBytes { return .tooLarge }
            formats[type.rawValue] = d
        }
        if formats.isEmpty { return .empty }

        let plain = pb.string(forType: .string)
        let hasText = !(plain ?? "").trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        let keys = Set(formats.keys)
        let kind: ClipKind
        if hasText {
            kind = keys.isDisjoint(with: richTypes) ? Classifier.kind(forPlainText: plain!) : .rich
        } else {
            kind = keys.isDisjoint(with: imageTypes) ? .other : .image
        }
        let hash: String
        if hasText {
            hash = ContentHash.of(text: plain!)
        } else if let img = imageTypes.sorted().compactMap({ formats[$0] }).first {
            hash = ContentHash.of(data: img)
        } else {
            hash = ContentHash.of(data: formats.keys.sorted().reduce(into: Data()) { $0.append(formats[$1]!) })
        }
        return .clip(ClipDraft(formats: formats, plainText: hasText ? plain : nil, fileURLs: [], kind: kind,
                               contentHash: hash, sourceBundleID: sourceBundleID))
    }
}

public enum PasteboardWriter {
    /// Marks Recall's own writes so the watcher doesn't record them as new copies.
    public static let ownType = NSPasteboard.PasteboardType("app.recall.own")

    public static func write(formats: [String: Data], plainOnly: Bool, to pb: NSPasteboard) {
        pb.clearContents()
        if let list = formats[fileListType], !plainOnly {
            let urls = String(decoding: list, as: UTF8.self).split(separator: "\n").compactMap { URL(string: String($0)) }
            pb.writeObjects(urls as [NSURL])
            pb.addTypes([ownType], owner: nil)
            pb.setData(Data(), forType: ownType)
            return
        }
        let plainKey = NSPasteboard.PasteboardType.string.rawValue
        let chosen = plainOnly ? formats.filter { $0.key == plainKey } : formats
        pb.declareTypes(chosen.keys.sorted().map { .init($0) } + [ownType], owner: nil)
        for (type, data) in chosen { pb.setData(data, forType: .init(type)) }
        pb.setData(Data(), forType: ownType)
    }
}
